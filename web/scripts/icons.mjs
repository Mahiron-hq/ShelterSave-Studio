import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"

const dir = resolve(import.meta.dirname, "..")
const map = {
  undo: "undo-2", redo: "redo-2", save: "save", open: "folder-open", search: "search",
  settings: "settings", users: "users", house: "house", layers: "layers", trash: "trash-2",
  plus: "plus", copy: "copy", check: "check", x: "x", warn: "triangle-alert", alert: "circle-alert",
  info: "info", history: "history", download: "download", upload: "upload", reset: "rotate-ccw",
  shield: "shield", paw: "paw-print", sword: "sword", shirt: "shirt", wrench: "wrench",
  sort: "arrow-up-down", external: "external-link", lock: "lock", help: "circle-help",
  pencil: "pencil", userPlus: "user-plus", heartPulse: "heart-pulse", radiation: "radiation",
  smile: "smile", dna: "dna", archive: "archive", scroll: "scroll-text", flag: "flag",
  sparkles: "sparkles", badge: "badge-check", skull: "skull", star: "star", menu: "menu",
  chevronDown: "chevron-down", chevronRight: "chevron-right", fileUp: "file-up", monitor: "monitor",
  smartphone: "smartphone", minus: "minus", filter: "filter", image: "image", palette: "palette",
  hammer: "hammer", map: "map", clock: "clock", package: "package", bot: "bot", gift: "gift",
}
const out = []
for (const [k, v] of Object.entries(map)) {
  const f = resolve(dir, `node_modules/lucide-static/icons/${v}.svg`)
  if (!existsSync(f)) throw new Error(`missing icon ${v}`)
  let s = readFileSync(f, "utf8").replace(/<!--[\s\S]*?-->/g, "").replace(/\s*\n\s*/g, " ").trim()
  s = s
    .replace(/ class="[^"]*"/, "")
    .replace("<svg ", '<svg aria-hidden="true" focusable="false" ')
    .replace('width="24" height="24"', 'width="1em" height="1em"')
  out.push(`  ${k}: ${JSON.stringify(s)},`)
}
writeFileSync(
  resolve(dir, "src/lib/icons.ts"),
  `// Lucide icons (ISC license), generated by scripts/icons.mjs.\nexport const icons = {\n${out.join("\n")}\n} as const\n\nexport type IconName = keyof typeof icons\n`,
)
